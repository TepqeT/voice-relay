// The site speaks French and English. The language comes from the "lang"
// cookie (set by the switch in the header), else the browser's
// Accept-Language, else English.

const langCookie = "vr_lang"

var languages = []string{"fr", "en"}

func validLang(l string) bool { return l == "fr" || l == "en" }

// langFor picks the page language of r.
func langFor(r *http.Request) string {
	if c, err := r.Cookie(langCookie); err == nil && validLang(c.Value) {
		return c.Value
	}
	for _, part := range strings.Split(r.Header.Get("Accept-Language"), ",") {
		tag := strings.ToLower(strings.TrimSpace(strings.SplitN(part, ";", 2)[0]))
		switch {
		case strings.HasPrefix(tag, "fr"):
			return "fr"
		case strings.HasPrefix(tag, "en"):
			return "en"
		}
	}
	return "en"
}

// tr returns the translator of lang: tr(key, args...) formats with fmt.
func tr(lang string) func(key string, args ...any) string {
	d := messages[lang]
	return func(key string, args ...any) string {
		s, ok := d[key]
		if !ok {
			s, ok = messages["en"][key]
		}
		if !ok {
			return key
		}
		if len(args) > 0 {
			return fmt.Sprintf(s, args...)
		}
		return s
	}
}

// dateFor formats a day in lang.
func dateFor(lang string, t time.Time) string {
	if lang == "en" {
		return t.Format("Jan 2, 2006")
	}
	return t.Format("02/01/2006")
}

